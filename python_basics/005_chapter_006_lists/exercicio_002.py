'''
Faça um programa que leia duas listas e que gere uma terceira com
os elementos das duas primeiras.
'''

# Exemplo de listas definidas ou lidas do utilizador
lista1 = [1, 2, 3, 4]
lista2 = [5, 6, 7, 8]

# Cria a terceira lista combinando as duas primeiras
lista3 = lista1 + lista2

print(f"Lista 1: {lista1}")
print(f"Lista 2: {lista2}")
print(f"Lista 3 (combinada): {lista3}")
